-- 0300: The OPC UA vocabulary seeds more of what its NodeSets describe.
--
-- The OPC UA tab held 75 data points, and the OPC Foundation's NodeSets declare more scalars that a
-- device can publish over Sparkplug B than that. This adds 49 of them, and a seventh companion
-- specification:
--
--   * OPC 40001-2 Machinery Process Values (v1.00.0): the shape of a process value, which OPC 40540's
--     ProcessValueAMType subtypes. Its eight rows are the reading (AnalogSignal), the setpoint, the
--     status, the percentage and the four limits.
--   * OPC 40010 Robotics, 11 rows: the controller's temperature, fans, input voltage, energy and
--     start-up, a motor's temperature, load and brake, and whether a task program is loaded.
--   * OPC 40001 Machinery, 10 rows: the operation counters and the identification a machine can carry
--     beyond the six already seeded.
--   * OPC 40501 Machine Tools, 10 rows, with three groups of their own: Laser, EDMGenerator and
--     Stacklight.
--   * OPC 40540 Additive Manufacturing, 5 rows: the feedstock's identity and function, and the
--     machine's technology.
--   * OPC 30050 PackML, 3 rows, and OPC 40001-4 Machinery Energy, 2 rows.
--
-- WHERE THE ROWS ARE. 0002 is released and is not regenerated, so the rows are a block of this file,
-- written by scripts/generate-opcua-vocabulary.mjs from the NodeSets and checked by
-- scripts/check-opcua-seed-sync.mjs, which holds 0002's block to the same rules. The three marked
-- regions below are the block: the metric_groups this file registers, the rows, and the COMMENT on the
-- table, which now names seven specifications.
--
-- THE ProcessValue GROUP changes its description, because OPC 40001-2's rows join OPC 40540's in it.
-- 0002 registers it ON CONFLICT DO NOTHING, so a database that holds it keeps the old text unless this
-- file replaces it. The UPDATE is guarded on that old text: a description an Administrator has since
-- edited is left alone, and a replay matches no row.
--
-- A replay changes nothing: the rows are ON CONFLICT (companion_spec, name) DO UPDATE, the groups
-- ON CONFLICT DO NOTHING, and the UPDATE has nothing left to match. No function, view or column is
-- changed, so there is no -- Redefines line. The Audit Trail has no row for any of it: neither table
-- is audited.
--
-- Reasoning: supabase/README.md, "The OPC UA vocabulary seeds more of what its NodeSets describe
-- (0300)". Idempotent.
--
-- WHAT WAS AND WAS NOT CONFIRMED AGAINST THE SOURCE. Every browse name, datatype and NodeId is read
-- from the NodeSet at the version pinned in the generator, which fails when a pin moves. The
-- descriptions are curated: 30 follow the NodeSet's own Description, and the other 19 are written
-- from the specification's reference page for the type (linked from the NodeSet) or from the
-- enumeration the NodeSet defines. The units are ours: no NodeSet fixes one for these variables.
-- OPC 40001-2's ids sit in its own namespace, http://opcfoundation.org/UA/Machinery/ProcessValues/.

