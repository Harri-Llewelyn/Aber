#!/usr/bin/env node
/**
 * Mirror the platform playbook into a module the edge runtime can import.
 *
 * An edge-runtime user worker has no filesystem access, so what `forge-sweep` publishes into the
 * forge as `platform/gateway-platform`, and what `gateway-bundle` and `gateway-install` hand to an
 * appliance, has to reach them as code: this writes every file under forge/gateway-platform/
 * (the playbook, the installer and, under appliance/, the compose project the appliance runs)
 * into supabase/functions/_shared/gatewayPlatform.generated.ts as one object, with a digest over
 * the lot that the published repository carries in `.acs/manifest.json`, so a sweep can tell in
 * one read whether the forge holds what this build ships. A generated module rather than
 * environment variables: a directory of files does not fit one variable per file, and a module
 * import needs no entry in main/index.ts's allow-list.
 *
 * THE COPY IS COMMITTED, like the chart mirrors: the functions image builds from the tree with no
 * generation step. `--check` fails when it is stale, which CI runs.
 *
 *   node scripts/sync-gateway-platform.mjs            # write it
 *   node scripts/sync-gateway-platform.mjs --check    # exit 1 if stale (CI)
 */
import { createHash } from 'node:crypto';
import { existsSync, readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const REPO_ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const PLAYBOOK_DIR = join(REPO_ROOT, 'forge', 'gateway-platform');
const TARGET = join(REPO_ROOT, 'supabase', 'functions', '_shared', 'gatewayPlatform.generated.ts');

/** Every file under a directory, as repository-relative POSIX paths, sorted. */
function walk(dir, prefix = '') {
  const out = [];
  for (const entry of readdirSync(dir).sort()) {
    const full = join(dir, entry);
    const rel = prefix ? `${prefix}/${entry}` : entry;
    if (statSync(full).isDirectory()) out.push(...walk(full, rel));
    else out.push({ path: rel, full });
  }
  return out;
}

const files = {};
for (const { path, full } of walk(PLAYBOOK_DIR)) {
  files[path] = readFileSync(full, 'utf8');
}

for (const [path, text] of Object.entries(files)) {
  if (text.includes('\r')) {
    console.error(`${path} carries a carriage return; the repository forces LF (.gitattributes) and the forge must hold the same bytes`);
    process.exit(1);
  }
}

const sha256 = (s) => createHash('sha256').update(s).digest('hex');
const digest = sha256(Object.keys(files).sort().map((p) => `${p}\n${sha256(files[p])}\n`).join(''));

const rendered = `// GENERATED by scripts/sync-gateway-platform.mjs from forge/gateway-platform/.
// DO NOT EDIT: edit the sources and run the script. CI fails when this file is stale.
//
// What forge-sweep publishes as platform/gateway-platform, and what gateway-bundle and
// gateway-install hand to an appliance: every file of the platform playbook, the installer, and
// the compose project under appliance/. The digest is what the published repository carries in
// .acs/manifest.json, so one read says whether the forge holds this build's copy.

export const GATEWAY_PLATFORM_DIGEST = ${JSON.stringify(digest)};

export const GATEWAY_PLATFORM_FILES: Record<string, string> = ${JSON.stringify(files, null, 2)};
`;

if (process.argv.includes('--check')) {
  const current = existsSync(TARGET) ? readFileSync(TARGET, 'utf8') : '';
  if (current !== rendered) {
    console.error(`${relative(REPO_ROOT, TARGET)} is stale. Run: node scripts/sync-gateway-platform.mjs`);
    process.exit(1);
  }
  console.log(`${relative(REPO_ROOT, TARGET)} is current (${Object.keys(files).length} files, digest ${digest.slice(0, 12)}).`);
} else {
  writeFileSync(TARGET, rendered);
  console.log(`wrote ${relative(REPO_ROOT, TARGET)}: ${Object.keys(files).length} files, digest ${digest.slice(0, 12)}`);
}
