#!/usr/bin/env node
/**
 * Mirror what the platform publishes into the forge into modules the edge runtime can import.
 *
 * An edge-runtime user worker has no filesystem access, so what `forge-sweep` publishes into the
 * forge, and what `gateway-bundle` and `gateway-install` hand to an appliance, has to reach them
 * as code: this writes every file of each published directory under `forge/` into its own module
 * under `supabase/functions/_shared/`, with a digest over the lot that the published repository
 * carries in `.acs/manifest.json`, so a sweep can tell in one read whether the forge holds what
 * this build ships. A generated module rather than environment variables: a directory of files
 * does not fit one variable per file, and a module import needs no entry in main/index.ts's
 * allow-list.
 *
 * ONE MODULE PER DIRECTORY, not one map of everything. `gateway-install` zips every entry of the
 * playbook's map into the `platform.zip` an appliance fetches, so a second directory folded into
 * that map would be installed on every appliance in the fleet.
 *
 * THE COPIES ARE COMMITTED, like the chart mirrors: the functions image builds from the tree with
 * no generation step. `--check` fails when one is stale, which CI runs.
 *
 *   node scripts/sync-gateway-platform.mjs            # write them
 *   node scripts/sync-gateway-platform.mjs --check    # exit 1 if stale (CI)
 */
import { createHash } from 'node:crypto';
import { existsSync, readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const REPO_ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');

/**
 * What is published, and under which names. Adding a row is the whole of teaching the edge runtime
 * about a new forge repository; `forge/README.md` says what else a new one needs.
 */
const PUBLISHED = [
  {
    source: join('forge', 'gateway-platform'),
    module: 'gatewayPlatform.generated.ts',
    prefix: 'GATEWAY_PLATFORM',
    // Written into the generated file's header, already wrapped.
    what: [
      'What forge-sweep publishes as platform/gateway-platform, and what gateway-bundle and',
      'gateway-install hand to an appliance: every file of the platform playbook, the installer,',
      'and the compose project under appliance/.',
    ],
  },
  {
    source: join('forge', 'gateway-custom-example'),
    module: 'gatewayCustomExample.generated.ts',
    prefix: 'GATEWAY_CUSTOM_EXAMPLE',
    what: [
      'What forge-sweep publishes as platform/gateway-custom-example, a template repository a',
      'person copies when a gateway needs code of its own: a custom.yml and the compose project',
      'it builds. Untagged, and never handed to an appliance by the platform.',
    ],
  },
];

/** Every file under a directory, as directory-relative POSIX paths, sorted. */
function walk(dir, prefix = '') {
  const out = [];
  for (const entry of readdirSync(dir).sort()) {
    const full = join(dir, entry);
    const rel = prefix ? `${prefix}/${entry}` : entry;
    if (statSync(full).isDirectory()) out.push(...walk(full, rel));
    else out.push({ path: rel, full });
  }
  return out;
}

const sha256 = (s) => createHash('sha256').update(s).digest('hex');

function render({ source, module, prefix, what }) {
  const files = {};
  for (const { path, full } of walk(join(REPO_ROOT, source))) {
    files[path] = readFileSync(full, 'utf8');
  }

  for (const [path, text] of Object.entries(files)) {
    if (text.includes('\r')) {
      console.error(`${source}/${path} carries a carriage return; the repository forces LF (.gitattributes) and the forge must hold the same bytes`);
      process.exit(1);
    }
  }

  const posixSource = source.split(/[\\/]/).join('/');
  const digest = sha256(Object.keys(files).sort().map((p) => `${p}\n${sha256(files[p])}\n`).join(''));
  const text = `// GENERATED by scripts/sync-gateway-platform.mjs from ${posixSource}/.
// DO NOT EDIT: edit the sources and run the script. CI fails when this file is stale.
//
${what.map((line) => `// ${line}`).join('\n')}
// The digest is what the published repository carries in .acs/manifest.json, so one read says
// whether the forge holds this build's copy.

export const ${prefix}_DIGEST = ${JSON.stringify(digest)};

export const ${prefix}_FILES: Record<string, string> = ${JSON.stringify(files, null, 2)};
`;

  return { target: join(REPO_ROOT, 'supabase', 'functions', '_shared', module), text, digest, count: Object.keys(files).length };
}

const checking = process.argv.includes('--check');
let stale = false;

for (const spec of PUBLISHED) {
  const { target, text, digest, count } = render(spec);
  const shown = relative(REPO_ROOT, target).split(/[\\/]/).join('/');

  if (checking) {
    const current = existsSync(target) ? readFileSync(target, 'utf8') : '';
    if (current !== text) {
      console.error(`${shown} is stale. Run: node scripts/sync-gateway-platform.mjs`);
      stale = true;
      continue;
    }
    console.log(`${shown} is current (${count} files, digest ${digest.slice(0, 12)}).`);
  } else {
    writeFileSync(target, text);
    console.log(`wrote ${shown}: ${count} files, digest ${digest.slice(0, 12)}`);
  }
}

if (stale) process.exit(1);
