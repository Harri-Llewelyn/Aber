/**
 * What scripts/generate-qudt-vocabulary.mjs and scripts/check-qudt-seed-sync.mjs read from QUDT's
 * two vocabulary files, and the crosswalk from MTConnect's units to QUDT's.
 *
 * The files are Turtle (scripts/lib/turtle.mjs reads them). A quantity kind is `quantitykind:<Name>`
 * typed `qudt:QuantityKind`, a unit is `unit:<Name>` typed `qudt:Unit`, and a deprecated one says
 * `qudt:deprecated true`. QUDT issues these IRIs itself, so the seed carries them as they are.
 */

import { parseSubjects, valuesOf } from './turtle.mjs';

export const QUDT_VERSION = '3.5.2';
export const KIND_BASE = 'http://qudt.org/vocab/quantitykind/';
export const UNIT_BASE = 'http://qudt.org/vocab/unit/';

export const UNIT_MODULE_HEADER =
  `// GENERATED by scripts/generate-qudt-vocabulary.mjs from scripts/vocabularies/mtconnect-units-to-qudt.json.\n` +
  `// Do not edit it: change the crosswalk and re-run the generator. CI checks that the two agree.\n` +
  `// An MTConnect unit name and the QUDT 3.5.2 unit (CC BY 4.0, attribution to QUDT.org) that is exactly that unit.`;

const isDeprecated = (statements) => valuesOf(statements, 'qudt:deprecated').includes('true');
const isA = (statements, type) => valuesOf(statements, 'rdf:type').includes(type);

/**
 * The English label: `@en`, else `@en-US`, else one with no language tag. QUDT labels a term in up
 * to 23 languages, and 124 kinds have only an `@en-US` one.
 */
export function englishLabel(statements) {
  const labels = statements['rdfs:label'] || [];
  const pick = labels.find((t) => t.lang === 'en') ?? labels.find((t) => t.lang === 'en-US') ??
    labels.find((t) => !t.lang);
  return pick ? pick.value.replace(/\s+/g, ' ').trim() : null;
}
// ---- plain text ------------------------------------------------------------------------------------

/** What QUDT writes in LaTeX math and the character that stands for it in plain text. */
const SYMBOLS = {
  cdot: '·', circ: '°', times: '×', dots: '…', int: '∫', hbar: 'ħ', bigtriangleup: 'Δ', over: '/',
  alpha: 'α', beta: 'β', gamma: 'γ', epsilon: 'ε', varepsilon: 'ε', kappa: 'κ', varkappa: 'ϰ',
  lambda: 'λ', mu: 'μ', pi: 'π', phi: 'φ', psi: 'ψ', omega: 'ω', vartheta: 'ϑ', theta: 'θ', tau: 'τ',
  rho: 'ρ', nu: 'ν', rm: '', sin: 'sin', cos: 'cos', tan: 'tan', sqrt: '√', Delta: 'Δ', Lambda: 'Λ', Omega: 'Ω', Phi: 'Φ', Psi: 'Ψ',
};
/** Commands that wrap text and leave it as it is. */
const WRAPPERS = new Set(['textit', 'textbf', 'text', 'mathrm', 'mathbf', 'underline', 'dot']);
const HTML_ENTITIES = { '&nbsp;': ' ', '&amp;': '&', '&lt;': '<', '&gt;': '>', '&quot;': '"', '&apos;': "'" };

/**
 * `text` without its HTML tags, found by scanning for `<` ... `>` rather than by a pattern. A `<`
 * starts a tag only before a letter, a slash or a bang, so `a < b` is text.
 */
function withoutTags(text) {
  let out = '';
  let i = 0;
  while (i < text.length) {
    let open = text.indexOf('<', i);
    while (open >= 0 && !/[A-Za-z/!]/.test(text[open + 1] ?? '')) open = text.indexOf('<', open + 1);
    if (open < 0) break;
    const close = text.indexOf('>', open);
    if (close < 0) break;
    out += text.slice(i, open) + ' ';
    i = close + 1;
  }
  return out + text.slice(i);
}

/** The text of the balanced `{...}` group that starts at `from`, and where it ends; null if none does. */
function group(text, from) {
  if (text[from] !== '{') return null;
  let depth = 0;
  for (let i = from; i < text.length; i += 1) {
    if (text[i] === '{') depth += 1;
    else if (text[i] === '}' && (depth -= 1) === 0) return { content: text.slice(from + 1, i), end: i + 1 };
  }
  return null;
}

/** `text` with each LaTeX command written out: a wrapper by its text, a fraction as `a/b`, a symbol as itself. */
function withoutLatex(text) {
  let out = '';
  let i = 0;
  while (i < text.length) {
    if (text[i] !== '\\') { out += text[i]; i += 1; continue; }
    let end = i + 1;
    while (end < text.length && /[A-Za-z]/.test(text[end])) end += 1;
    const name = text.slice(i + 1, end);
    if (name === '') {                                     // a control symbol: \, \; \! or \ (a space)
      if (/[,;! ]/.test(text[end] ?? '')) { out += ' '; i = end + 1; } else { out += '\\'; i += 1; }
    } else if (WRAPPERS.has(name)) {
      const arg = group(text, end);                        // an unclosed brace leaves the text as it is
      out += arg ? withoutLatex(arg.content) : '';
      i = arg ? arg.end : end;
    } else if (name === 'frac') {
      const top = group(text, end);
      const bottom = top && group(text, top.end);
      out += top && bottom ? `${withoutLatex(top.content)}/${withoutLatex(bottom.content)}` : '';
      i = top && bottom ? bottom.end : end;
    } else if (name === 'color') {
      i = group(text, end)?.end ?? end;
    } else if (name in SYMBOLS) {
      out += SYMBOLS[name];
      i = end;
    } else {
      out += `\\${name}`;                                  // left for the caller to refuse
      i = end;
    }
  }
  return out;
}

/**
 * A description as plain text: HTML tags gone, LaTeX written out (`$\textit{Absolute Humidity}$` is
 * `Absolute Humidity`, `$\frac{M}{H^2}$ is `M/H^2`), whitespace collapsed. QUDT writes some of its
 * LaTeX with a backslash that Turtle reads as an escape, so `\\\textit` arrives as a backslash and a
 * tab and `\\\rho` as a backslash and a carriage return: those are put back first. A command this
 * does not know is an error, so a release that adds one is read before it is seeded, never published
 * with a stray backslash.
 */
export function plainText(value) {
  let text = String(value).replace(/\\([\t\r\f\b])/g, (_, control) => `\\${{ '\t': 't', '\r': 'r', '\f': 'f', '\b': 'b' }[control]}`);
  text = withoutTags(text);
  for (const [entity, character] of Object.entries(HTML_ENTITIES)) text = text.split(entity).join(character);
  text = withoutLatex(text.replace(/\$\$\$\$/g, ' ').replace(/\s*\^\s*\\circ/g, '\\circ'));
  text = text.replace(/[${}]/g, '').replace(/\s+/g, ' ').trim();

  const left = text.indexOf('\\');
  if (left >= 0) throw new Error(`a LaTeX command the reader does not know is left in: ${text.slice(Math.max(0, left - 40), left + 40)}`);
  return text;
}

/** The first literal written in English or with no language tag: 122 plain-text descriptions are German. */
const english = (terms = []) => terms.find((t) => !t.lang || t.lang === 'en' || t.lang === 'en-US')?.value;

/**
 * `qudt:plainTextDescription`, else `dcterms:description`, in English and as plain text; null where
 * there is neither.
 */
export function description(statements) {
  const text = english(statements['qudt:plainTextDescription']) ?? english(statements['dcterms:description']);
  const plain = text === undefined ? '' : plainText(text);
  return plain === '' ? null : plain;
}

const byIri = (a, b) => (a.semanticId < b.semanticId ? -1 : a.semanticId > b.semanticId ? 1 : 0);

/**
 * Every quantity kind that is not deprecated, as `{ semanticId, name, description }` in IRI order.
 * A subject that is not typed `qudt:QuantityKind` (the file holds one with only a wikidata match, and
 * no label) is not a kind, and a kind with no English label is refused rather than given a made-up name.
 */
export function quantityKinds(turtle) {
  const rows = [];
  for (const [local, statements] of parseSubjects(turtle, 'quantitykind:')) {
    if (!isA(statements, 'qudt:QuantityKind') || isDeprecated(statements)) continue;
    const name = englishLabel(statements);
    if (!name) throw new Error(`quantitykind:${local} has no label`);
    rows.push({ semanticId: KIND_BASE + local, name, description: description(statements) });
  }
  return rows.sort(byIri);
}

/**
 * Every unit, deprecated ones included, as a Map from its IRI to `{ semanticId, name, symbol,
 * uneceCode, deprecated }`. `uneceCode` is the first UN/ECE Recommendation 20 code QUDT gives the
 * unit, which is the only one for all but one unit (`QT_US` has two); null where it gives none.
 */
export function units(turtle) {
  const found = new Map();
  for (const [local, statements] of parseSubjects(turtle, 'unit:')) {
    if (!isA(statements, 'qudt:Unit')) continue;
    const name = englishLabel(statements);
    if (!name) throw new Error(`unit:${local} has no label`);
    const symbol = valuesOf(statements, 'qudt:symbol')[0];
    found.set(UNIT_BASE + local, {
      semanticId: UNIT_BASE + local,
      name,
      symbol: symbol ? symbol.replace(/\s+/g, ' ').trim() : null,
      uneceCode: valuesOf(statements, 'qudt:uneceCommonCode')[0] ?? null,
      deprecated: isDeprecated(statements),
    });
  }
  return found;
}

// ---- the crosswalk ---------------------------------------------------------------------------------

/** The unit IRIs a crosswalk reaches, once each, in IRI order. */
export function reachedUnitIris(crosswalk) {
  return [...new Set(Object.values(crosswalk.units).map((entry) => entry.unit).filter(Boolean))].sort();
}

/**
 * What is wrong with a crosswalk, as sentences: a name MTConnect's vocabulary holds that it lacks, a
 * name it has that MTConnect's does not, an IRI that is not in QUDT's units or is deprecated there, an
 * entry that maps to nothing without saying why, and one that says why while mapping. Empty when it is
 * sound.
 */
export function crosswalkProblems(crosswalk, mtconnectNames, qudtUnits) {
  const problems = [];
  const names = new Set(mtconnectNames);
  const mapped = Object.keys(crosswalk.units);
  for (const name of names) if (!(name in crosswalk.units)) problems.push(`${name} is an MTConnect unit and the crosswalk does not name it`);
  for (const name of mapped) if (!names.has(name)) problems.push(`${name} is in the crosswalk and is not an MTConnect unit the vocabulary holds`);
  for (const [name, entry] of Object.entries(crosswalk.units)) {
    if (entry.unit === null) {
      if (typeof entry.reason !== 'string' || entry.reason.trim() === '') problems.push(`${name} maps to nothing and gives no reason`);
      continue;
    }
    if ('reason' in entry) problems.push(`${name} maps to ${entry.unit} and also gives a reason for mapping to nothing`);
    const unit = qudtUnits.get(entry.unit);
    if (!unit) problems.push(`${name} maps to ${entry.unit}, which is not a unit in the QUDT file`);
    else if (unit.deprecated) problems.push(`${name} maps to ${entry.unit}, which QUDT deprecates`);
  }
  return problems;
}

/**
 * The module the AAS exporter reads: each MTConnect unit name that maps to a QUDT unit, and that
 * unit's IRI. Generated, so the exporter needs no read of the database and cannot drift from the
 * crosswalk the seed was built from.
 */
export function unitIdsModule(crosswalk, header) {
  const lines = Object.entries(crosswalk.units)
    .filter(([, entry]) => entry.unit)
    .map(([name, entry]) => `  ${JSON.stringify(name)}: ${JSON.stringify(entry.unit)},`);
  return `${header}\nexport const QUDT_UNIT_IDS: Readonly<Record<string, string>> = {\n${lines.join('\n')}\n};\n`;
}

/**
 * The MTConnect unit names the vocabulary holds, `UNIT` and `NATIVE_UNIT` kinds, read from the seed
 * the MTConnect generator wrote (0002). The crosswalk must name exactly these.
 */
export function mtconnectUnitNames(seedSql) {
  const rows = seedSql.matchAll(/^INSERT INTO public\.mtconnect_vocabulary VALUES \('(?:UNIT|NATIVE_UNIT)', '([^']+)',/gm);
  return [...rows].map((row) => row[1]);
}
